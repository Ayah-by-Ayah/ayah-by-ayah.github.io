def vk(t):  # skeleton key for matching a lemma by its past form without short vowels
    return re.sub('[ً-ٰ]', '', t or '').replace('ٱ', 'ا').replace('أ', 'ا').replace('إ', 'ا').replace('آ', 'ا').replace('ى', 'ي')

def canon(t):  # base letters with their marks in one fixed order (the same word can be typed with the marks in either order)
    out = []
    for ch in t:
        if re.match('[ً-ٰ]', ch) and out: out[-1][1].append(ch)
        else: out.append([ch, []])
    return ''.join(c + ''.join(sorted(m)) for c, m in out)

